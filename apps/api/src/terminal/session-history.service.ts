// =============================================================================
// The one place that reads a tmux pane (issue #56)
// =============================================================================
//
// `capture-pane` appears ONLY in this file (guard spec:
// `test/terminal-ai/capture-boundary.spec.ts`). Everything that needs terminal
// text (the history download, the AI context pipeline) goes through here, so a
// capture can never reach a model without passing `TerminalContextService`'s
// consent, switch and redaction gates.
// =============================================================================

import { BadRequestException, HttpException, HttpStatus, Injectable } from '@nestjs/common';

import type { OwnerScope } from '../common/types/owner-scope';
import { ServerProfilesService } from '../server-profiles/server-profiles.service';
import { HostKeyError } from '../ssh/host-key.error';
import { hostKeyErrorToHttp } from '../ssh/host-key-http';
import { SessionsService } from './sessions.service';
import { SshService } from './ssh.service';

export interface CaptureOptions {
  /** Last N lines of scrollback; omitted means the whole history. */
  lines?: number;
  /** `-J`: join wrapped lines. The history download keeps the raw wrapping (`false`). Default `true`. */
  joinWrapped?: boolean;
}

/** What a capture needs from a session row. */
export interface CapturableSession {
  id: string;
  status: string;
  serverProfileId: string;
  tmuxSessionId: string;
}

// tmux session ids are generated by ShellKeep; refuse anything that is not shell-inert.
const SAFE_TMUX_ID = /^[A-Za-z0-9_.-]+$/;

@Injectable()
export class SessionHistoryService {
  constructor(
    private readonly sessions: SessionsService,
    private readonly ssh: SshService,
    private readonly profiles: ServerProfilesService,
  ) {}

  /** Captures a session's scrollback as plain text. Ownership is checked by `SessionsService.findOne`. */
  async capture(sessionId: string, scope: OwnerScope, options: CaptureOptions = {}): Promise<string> {
    const session = await this.sessions.findOne(sessionId, scope);
    return this.captureSession(session, scope, options);
  }

  /** As {@link capture}, for a session row the caller already loaded and authorised. */
  async captureSession(
    session: CapturableSession,
    scope: OwnerScope,
    options: CaptureOptions = {},
  ): Promise<string> {
    const { lines, joinWrapped = true } = options;
    const start = lines !== undefined && lines > 0 ? `-${Math.floor(lines)}` : '-';
    const command =
      `tmux capture-pane -p ${joinWrapped ? '-J ' : ''}-S ${start} -t ${this.tmuxTarget(session)}`;
    return this.run(session, scope, command, 'Failed to retrieve terminal history from remote server');
  }

  /** The pane's current working directory, or `null` when it cannot be read. */
  async currentPath(session: CapturableSession, scope: OwnerScope): Promise<string | null> {
    try {
      const out = await this.run(
        session,
        scope,
        `tmux display-message -p -t ${this.tmuxTarget(session)} '#{pane_current_path}'`,
        'Failed to read the working directory',
      );
      const path = out.trim();
      return path === '' ? null : path;
    } catch {
      return null;
    }
  }

  private tmuxTarget(session: CapturableSession): string {
    if (!SAFE_TMUX_ID.test(session.tmuxSessionId)) {
      throw new BadRequestException('Invalid tmux session identifier');
    }
    return session.tmuxSessionId;
  }

  private async run(
    session: CapturableSession,
    scope: OwnerScope,
    command: string,
    failureMessage: string,
  ): Promise<string> {
    if (session.status === 'terminated') {
      throw new BadRequestException('Cannot download history for a terminated session');
    }
    const profile = await this.profiles.getDecryptedProfileForSession(session.serverProfileId, scope, 'history');
    try {
      return await this.ssh.execForOutput(profile, command);
    } catch (error) {
      // A refused host key is the user's decision to make, not a gateway failure.
      if (error instanceof HostKeyError) throw hostKeyErrorToHttp(error, session.serverProfileId);
      const message = error instanceof Error ? error.message : String(error);
      if (
        message.includes('session not found') ||
        message.includes('no server running') ||
        message.includes("can't find")
      ) {
        throw new HttpException('Remote tmux session no longer exists', HttpStatus.NOT_FOUND);
      }
      throw new HttpException(failureMessage, HttpStatus.BAD_GATEWAY);
    }
  }
}
